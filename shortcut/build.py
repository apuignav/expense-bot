#!/usr/bin/env python3
"""Build shortcut/wallet-expense.shortcut from the Cherri source.

Cherri cannot add a Wallet notification trigger. This script compiles the
source with Cherri, edits the property list (plist) to add the trigger and
to read the notification through it, fills in the deployment values from
Proton Pass, and then signs the result. The shop table comes from
shops.json.

Run from the repository root: python3 shortcut/build.py
Set CHERRI to the path of the Cherri binary (default: cherri on the PATH).
"""
import json
import os
import plistlib
import subprocess
import sys
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "wallet-expense.cherri"
DEBUG_PLIST = HERE / "wallet-expense.plist"
SHOPS_JSON = HERE / "shops.json"
SHOPS_CHERRI = HERE / "shops.generated.cherri"
DEBUG_FILES = [
    HERE / "wallet-expense.plist",
    HERE / "wallet-expense_processed.cherri",
    HERE / "wallet-expense_unsigned.shortcut",
    SHOPS_CHERRI,
]
TOKEN_PLACEHOLDER = "__SENDER_BOT_TOKEN__"
CHAT_PLACEHOLDER = "__CHAT_ID__"
BOT_PLACEHOLDER = "__BOT_USERNAME__"
PLACEHOLDERS = [TOKEN_PLACEHOLDER, CHAT_PLACEHOLDER, BOT_PLACEHOLDER]
PATCHED_XML = HERE / "wallet-expense.patched.plist"
PATCHED_BIN = HERE / "wallet-expense.patched.shortcut"
OUTPUT = HERE / "wallet-expense.shortcut"
MIN_VERSION = 3010


def fail(message):
    sys.exit(f"error: {message}")


def make_trigger():
    return {
        "WFTriggerIdentifier": "WFNotificationTrigger",
        "WFTriggerSerializedParameters": {
            "Conditions": {
                "Value": {
                    "WFActionParameterFilterPrefix": 1,
                    "WFActionParameterFilterTemplates": [],
                    "WFContentPredicateBoundedDate": False,
                },
                "WFSerializationType": "WFContentPredicateTableTemplate",
            },
            "SelectedApps": {
                "BundleIdentifier": "com.apple.Passbook",
                "Name": "Wallet",
                "TeamIdentifier": "0000000000",
            },
        },
        "WFTriggerUUID": str(uuid.uuid4()).upper(),
    }


def is_shortcut_input(node):
    return (
        isinstance(node, dict)
        and node.get("Type") == "ExtensionInput"
        and node.get("VariableName") == "ShortcutInput"
    )


def count_inputs(node):
    if is_shortcut_input(node):
        return 1 + sum(count_inputs(v) for v in node.values())
    if isinstance(node, dict):
        return sum(count_inputs(v) for v in node.values())
    if isinstance(node, list):
        return sum(count_inputs(v) for v in node)
    return 0


def replace_inputs(node):
    """Replace input references in place. Return how many were replaced."""
    count = 0
    if isinstance(node, dict):
        if is_shortcut_input(node):
            node["Type"] = "TriggerOutput"
            node["TriggerIdentifier"] = "WFNotificationTrigger"
            del node["VariableName"]
            count += 1
        for value in node.values():
            count += replace_inputs(value)
    elif isinstance(node, list):
        for value in node:
            count += replace_inputs(value)
    return count


def load_shops():
    try:
        with open(SHOPS_JSON, encoding="utf-8") as handle:
            shops = json.load(handle)
    except (OSError, ValueError) as error:
        fail(f"cannot read {SHOPS_JSON.name}: {error}")
    if not isinstance(shops, list):
        fail(f"{SHOPS_JSON.name} must be a list of objects")
    for index, shop in enumerate(shops, start=1):
        if not isinstance(shop, dict):
            fail(f"{SHOPS_JSON.name} entry {index} must be an object")
        for key in ("match", "name"):
            value = shop.get(key)
            if not isinstance(value, str) or not value.strip():
                fail(f"{SHOPS_JSON.name} entry {index}: '{key}' must be a non-empty string")
    return shops


def cherri_string(value):
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped.replace("\n", " ") + '"'


def write_shops_cherri(shops):
    """Write the Cherri if chain. The first matching entry wins."""
    lines = ["// Generated by build.py from shops.json. Do not edit."]
    for index, shop in enumerate(shops):
        keyword = "if" if index == 0 else "} else if"
        lines.append(
            f"{keyword} @subtitle contains {cherri_string(shop['match'])} {{"
        )
        lines.append(f"    @shop = {cherri_string(shop['name'])}")
    if shops:
        lines.append("}")
    SHOPS_CHERRI.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_config():
    vault = os.environ.get("PASS_VAULT", "Server")
    item = os.environ.get("PASS_ITEM", "ExpenseBot Shortcut config")
    command = [
        "pass-cli", "item", "view",
        "--vault-name", vault, "--item-title", item, "--output", "json",
    ]
    try:
        result = subprocess.run(command, capture_output=True, text=True, check=True)
        note = json.loads(result.stdout)["item"]["content"]["note"]
        config = json.loads(note)
    except FileNotFoundError:
        fail("pass-cli is not installed")
    except subprocess.CalledProcessError:
        fail("the command 'pass-cli item view' failed (is the session logged in?)")
    except (ValueError, KeyError, TypeError):
        fail("the Pass item does not hold a JSON note at .item.content.note")
    if not isinstance(config, dict):
        fail("the Pass note must be a JSON object")
    for key, kind in (("token", str), ("chat_id", int), ("bot_username", str)):
        value = config.get(key)
        if not isinstance(value, kind) or isinstance(value, bool) or value == "":
            fail(f"the Pass note key '{key}' is missing or has the wrong type")
    return {
        TOKEN_PLACEHOLDER: config["token"],
        CHAT_PLACEHOLDER: str(config["chat_id"]),
        BOT_PLACEHOLDER: config["bot_username"],
    }


def substitute(node, values):
    """Replace placeholders in all strings. Return the new node and counts."""
    counts = {key: 0 for key in values}
    def walk(item):
        if isinstance(item, str):
            for key, value in values.items():
                if key in item:
                    counts[key] += item.count(key)
                    item = item.replace(key, value)
            return item
        if isinstance(item, dict):
            return {walk(k): walk(v) for k, v in item.items()}
        if isinstance(item, list):
            return [walk(v) for v in item]
        return item
    return walk(node), counts


def has_placeholder(node, keys):
    if isinstance(node, str):
        return any(key in node for key in keys)
    if isinstance(node, dict):
        return any(has_placeholder(k, keys) or has_placeholder(v, keys) for k, v in node.items())
    if isinstance(node, list):
        return any(has_placeholder(v, keys) for v in node)
    return False


def cleanup():
    for path in DEBUG_FILES + [PATCHED_BIN]:
        path.unlink(missing_ok=True)


def main():
    cherri = os.environ.get("CHERRI", "cherri")
    shops = load_shops()
    values = load_config()
    try:
        write_shops_cherri(shops)
        subprocess.run(
            [cherri, str(SOURCE), "--skip-sign", "-d"],
            check=True,
            stdout=subprocess.DEVNULL
        )
        with open(DEBUG_PLIST, "rb") as handle:
            plist = plistlib.load(handle)

        before = count_inputs(plist)
        if before == 0:
            fail("no ExtensionInput references found in the compiled plist")

        plist["WFWorkflowTriggers"] = [make_trigger()]
        replaced = replace_inputs(plist)
        plist["WFWorkflowMinimumClientVersion"] = MIN_VERSION
        plist["WFWorkflowMinimumClientVersionString"] = str(MIN_VERSION)

        remaining = count_inputs(plist)
        if remaining:
            fail(f"{remaining} ExtensionInput reference(s) to ShortcutInput remain")

        plist["WFWorkflowImportQuestions"] = []

        # Inspection copy: chat ID and bot username filled in, token kept as
        # a placeholder.
        public = {k: v for k, v in values.items() if k != TOKEN_PLACEHOLDER}
        inspect, counts = substitute(plist, public)
        for key, found in counts.items():
            if not found:
                fail(f"placeholder {key} was not found in the compiled plist")
        if has_placeholder(inspect, list(public)):
            fail("a placeholder is still present after the replacement")
        if not has_placeholder(inspect, [TOKEN_PLACEHOLDER]):
            fail(f"placeholder {TOKEN_PLACEHOLDER} was not found in the compiled plist")
        with open(PATCHED_XML, "wb") as handle:
            plistlib.dump(inspect, handle, fmt=plistlib.FMT_XML)

        final, _ = substitute(
            inspect, {TOKEN_PLACEHOLDER: values[TOKEN_PLACEHOLDER]}
        )
        if has_placeholder(final, PLACEHOLDERS):
            fail("a placeholder is still present after the replacement")
        with open(PATCHED_BIN, "wb") as handle:
            plistlib.dump(final, handle, fmt=plistlib.FMT_BINARY)

        subprocess.run(
            [
                "/usr/bin/shortcuts", "sign", "--mode", "anyone",
                "--input", str(PATCHED_BIN), "--output", str(OUTPUT),
            ],
            check=True,
        )
        print(f"Replaced {replaced} input reference(s) (found {before}).")
        print(f"Wrote {OUTPUT.relative_to(HERE.parent)}")
    except subprocess.CalledProcessError as error:
        fail(f"command failed: {error}")
    finally:
        cleanup()


if __name__ == "__main__":
    main()
